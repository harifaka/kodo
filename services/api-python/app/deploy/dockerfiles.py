"""Stack-specific multi-stage Dockerfile templates.

Pure text: the caller supplies the stack, project name and port; nothing is read or written.
"""

from __future__ import annotations

from app.deploy.spec import CSHARP_DOTNET, CSHARP_WPF, HEALTH_PATHS, NODEJS, PYTHON
from app.generators.base import pascal_case


def dockerfile_for(stack: str, project_name: str, port: int) -> str:
    if stack == NODEJS:
        return node_dockerfile(port)
    if stack in (CSHARP_DOTNET, CSHARP_WPF):
        return dotnet_dockerfile(project_name, port)
    if stack == PYTHON:
        return python_dockerfile(port)
    return spring_dockerfile(port)


def healthcheck(stack: str, port: int) -> str:
    if stack == PYTHON:
        # Single quotes keep the command YAML-friendly; the runtime image has no curl/wget.
        return (
            "python -c 'import urllib.request; urllib.request.urlopen("
            f'"http://127.0.0.1:{port}{HEALTH_PATHS[PYTHON]}", timeout=3)\''
        )
    return f"wget -qO- http://127.0.0.1:{port}{HEALTH_PATHS.get(stack, '/health')} || exit 1"


def spring_dockerfile(port: int) -> str:
    return f"""# syntax=docker/dockerfile:1
# Generated by Kodo Deploy Studio - multi-stage build, non-root runtime.
FROM maven:3.9-eclipse-temurin-21 AS build
WORKDIR /workspace
COPY pom.xml ./
RUN mvn -B -q -DskipTests dependency:go-offline
COPY src ./src
RUN mvn -B -q -DskipTests package \\
    && cp target/*.jar /workspace/app.jar

FROM eclipse-temurin:21-jre-alpine AS runtime
RUN addgroup -S kodo && adduser -S kodo -G kodo
WORKDIR /app
COPY --from=build --chown=kodo:kodo /workspace/app.jar ./app.jar
ENV SERVER_PORT={port}
EXPOSE {port}
USER kodo
HEALTHCHECK --interval=30s --timeout=5s --start-period=60s --retries=3 \\
  CMD {healthcheck("spring-boot", port)}
ENTRYPOINT ["java", "-XX:MaxRAMPercentage=75", "-jar", "/app/app.jar"]
"""


def node_dockerfile(port: int) -> str:
    return f"""# syntax=docker/dockerfile:1
# Generated by Kodo Deploy Studio - multi-stage build, non-root runtime.
FROM node:22-alpine AS build
WORKDIR /app
COPY package*.json ./
RUN if [ -f package-lock.json ]; then npm ci; else npm install; fi
COPY . .
RUN npm run build

FROM node:22-alpine AS runtime
RUN addgroup -S kodo && adduser -S kodo -G kodo
WORKDIR /app
ENV NODE_ENV=production
ENV PORT={port}
COPY package*.json ./
RUN if [ -f package-lock.json ]; then npm ci --omit=dev; else npm install --omit=dev; fi \\
    && npm cache clean --force
COPY --from=build --chown=kodo:kodo /app/dist ./dist
USER kodo
EXPOSE {port}
HEALTHCHECK --interval=30s --timeout=5s --start-period=20s --retries=3 \\
  CMD {healthcheck("nodejs", port)}
CMD ["node", "dist/index.js"]
"""


def dotnet_dockerfile(project_name: str, port: int) -> str:
    assembly = f"{pascal_case(project_name)}.dll"
    return f"""# syntax=docker/dockerfile:1
# Generated by Kodo Deploy Studio - multi-stage build, non-root runtime.
FROM mcr.microsoft.com/dotnet/sdk:8.0 AS build
WORKDIR /src
COPY . .
RUN dotnet restore
RUN dotnet publish -c Release -o /app/publish /p:UseAppHost=false

FROM mcr.microsoft.com/dotnet/aspnet:8.0-alpine AS runtime
RUN addgroup -S kodo && adduser -S kodo -G kodo
WORKDIR /app
COPY --from=build --chown=kodo:kodo /app/publish .
ENV ASPNETCORE_URLS=http://+:{port}
ENV DOTNET_EnableDiagnostics=0
EXPOSE {port}
USER kodo
HEALTHCHECK --interval=30s --timeout=5s --start-period=20s --retries=3 \\
  CMD {healthcheck("csharp-dotnet", port)}
ENTRYPOINT ["dotnet", "{assembly}"]
"""


def python_dockerfile(port: int) -> str:
    return f"""# syntax=docker/dockerfile:1
# Generated by Kodo Deploy Studio - multi-stage build, non-root runtime.
# The runtime command assumes the FastAPI app lives at app.main:app (adjust CMD if your package root differs).
FROM python:3.12-slim AS build
ENV PIP_DISABLE_PIP_VERSION_CHECK=1 \\
    PIP_NO_CACHE_DIR=1
WORKDIR /app
COPY . .
RUN python -m venv /opt/venv \\
    && if [ -f requirements.txt ]; then /opt/venv/bin/pip install -r requirements.txt; \\
       else /opt/venv/bin/pip install .; fi

FROM python:3.12-slim AS runtime
RUN groupadd --system --gid 10001 kodo \\
    && useradd --system --uid 10001 --gid kodo --create-home kodo
WORKDIR /app
ENV PATH="/opt/venv/bin:$PATH" \\
    PYTHONUNBUFFERED=1 \\
    PYTHONDONTWRITEBYTECODE=1
COPY --from=build /opt/venv /opt/venv
COPY --from=build --chown=kodo:kodo /app /app
EXPOSE {port}
USER kodo
HEALTHCHECK --interval=30s --timeout=5s --start-period=30s --retries=3 \\
  CMD {healthcheck("python", port)}
CMD ["uvicorn", "app.main:app", "--host", "0.0.0.0", "--port", "{port}"]
"""


def sidecar_dockerfile(port: int) -> str:
    return f"""# syntax=docker/dockerfile:1
# Generated by Kodo Deploy Studio.
# WPF is a Windows-only desktop UI and cannot run in a Linux container. This optional sidecar
# hosts the API the desktop app talks to; adjust the project path below to your API project.
FROM mcr.microsoft.com/dotnet/sdk:8.0 AS build
WORKDIR /src
COPY . .
RUN dotnet restore ./Sidecar/Sidecar.csproj
RUN dotnet publish ./Sidecar/Sidecar.csproj -c Release -o /app/publish /p:UseAppHost=false

FROM mcr.microsoft.com/dotnet/aspnet:8.0-alpine AS runtime
RUN addgroup -S kodo && adduser -S kodo -G kodo
WORKDIR /app
COPY --from=build --chown=kodo:kodo /app/publish .
ENV ASPNETCORE_URLS=http://+:{port}
EXPOSE {port}
USER kodo
HEALTHCHECK --interval=30s --timeout=5s --start-period=20s --retries=3 \\
  CMD {healthcheck("csharp-wpf", port)}
ENTRYPOINT ["dotnet", "Sidecar.dll"]
"""


